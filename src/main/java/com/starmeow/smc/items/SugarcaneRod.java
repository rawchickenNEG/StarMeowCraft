import java.util.UUID;

public class SugarcaneRod extends SwordItem {

    public SugarcaneRod(Tier p_43269_, int p_43270_, float p_43271_, Properties p_43272_) {
        super(p_43269_, p_43270_, p_43271_, p_43272_);
    }

    @Override
    public Multimap<Attribute, AttributeModifier> getAttributeModifiers(EquipmentSlot slot, ItemStack stack)
    {
        ImmutableMultimap.Builder<Attribute, AttributeModifier> builder = ImmutableMultimap.builder();
        builder.putAll(this.getDefaultAttributeModifiers(slot));
        if (slot == EquipmentSlot.MAINHAND) {
            builder.put(ForgeMod.ENTITY_REACH.get(), new AttributeModifier(UUID.fromString("659a88ed-4709-4742-9604-6d0e7e97ebb7"), "atk_range", 3.0D, AttributeModifier.Operation.ADDITION));
        }
        return builder.build();
    }
}
